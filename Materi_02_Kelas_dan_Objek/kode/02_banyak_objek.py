# DEFINISI KELAS
# Kelas Produk didefinisikan di sini, dipakai di semua bagian
# ??????????????????????????????????????????????????????????
class Produk:
    """Merepresentasikan satu produk di toko/marketplace."""

    def __init__(self, nama, kategori, harga, stok):
        """
        Parameter:
            nama      (str): Nama produk
            kategori  (str): Kategori produk
            harga     (int): Harga dalam rupiah
            stok      (int): Jumlah stok tersedia
        """
        self.nama      = nama
        self.kategori  = kategori
        self.harga     = harga
        self.stok      = stok

    def info(self):
        """Tampilkan info produk dalam format tabel."""
        print(f"  {self.nama:<22} | {self.kategori:<12} | "
              f"Rp {self.harga:>10,.0f} | Stok: {self.stok:>3}")

    def terjual(self, jumlah):
        """
        Proses penjualan sejumlah 'jumlah' unit.
        Mengurangi stok jika stok mencukupi.
        """
        if jumlah > self.stok:
            print(f"  ??  [{self.nama}] Stok tidak cukup! "
                  f"Diminta: {jumlah}, Tersedia: {self.stok}")
            return False
        self.stok -= jumlah
        print(f"  [OK] [{self.nama}] Terjual {jumlah} unit. Sisa stok: {self.stok}")
        return True

    def harga_setelah_diskon(self, persen):
        """Mengembalikan harga setelah dikurangi diskon persen."""
        return self.harga * (1 - persen / 100)

    def __str__(self):
        """Representasi string objek saat di-print langsung."""
        return f"Produk('{self.nama}', Rp {self.harga:,.0f})"


# ?? Membuat katalog: list berisi banyak objek ????????????
katalog = [
    Produk("Laptop ASUS VivoBook", "Elektronik",  8_500_000, 10),
    Produk("Mouse Wireless",        "Elektronik",    150_000, 50),
    Produk("Keyboard Mechanical",   "Elektronik",    550_000, 25),
    Produk("Buku Python OOP",       "Buku",          120_000, 100),
    Produk("Tas Ransel Laptop",     "Aksesoris",     350_000, 30),
    Produk("Monitor 24 Inch",       "Elektronik",  2_800_000,  8),
    Produk("Headset Gaming",        "Elektronik",    450_000, 15),
]


# ??????????????????????????????????????????????????????????
# BAGIAN 1: TAMPILKAN SEMUA PRODUK
# ??????????????????????????????????????????????????????????
print("\n[INFO] 1. Seluruh Produk di Katalog:")
print("-" * 58)
print(f"  {'Nama':<22} | {'Kategori':<12} | {'Harga':>12} | Stok")
print("  " + "-" * 56)

for produk in katalog:
    produk.info()

# Output:
#   Laptop ASUS VivoBook   | Elektronik   |  Rp  8,500,000 | Stok:  10
#   Mouse Wireless         | Elektronik   |  Rp    150,000 | Stok:  50
#   ...


# ??????????????????????????????????????????????????????????
# BAGIAN 2: FILTER OBJEK (List Comprehension)
# ??????????????????????????????????????????????????????????
print("\n\n[INFO] 2. Filter - Hanya Produk Elektronik:")
print("-" * 58)

elektronik = [p for p in katalog if p.kategori == "Elektronik"]
print(f"  Ditemukan {len(elektronik)} produk elektronik:\n")
for p in elektronik:
    p.info()
# Output: hanya produk dengan kategori "Elektronik"

print("\n\n[INFO] 2b. Filter - Produk Harga < Rp 500.000:")
print("-" * 58)

murah = [p for p in katalog if p.harga < 500_000]
for p in murah:
    p.info()
# Output: Mouse, Buku, Tas Ransel


# ??????????????????????????????????????????????????????????
# BAGIAN 3: SIMULASI PENJUALAN
# ??????????????????????????????????????????????????????????
print("\n\n[INFO] 3. Simulasi Penjualan:")
print("-" * 58)

katalog[0].terjual(3)    # Laptop: stok 10 -> 7
katalog[1].terjual(60)   # Mouse: stok 50 -> tidak cukup!
katalog[3].terjual(5)    # Buku: stok 100 -> 95

# Cek stok Laptop setelah terjual
print(f"\n  Stok Laptop sekarang: {katalog[0].stok}")


# ??????????????????????????????????????????????????????????
# BAGIAN 4: DISKON - MENGGUNAKAN RETURN VALUE
# ??????????????????????????????????????????????????????????
print("\n\n[INFO] 4. Harga Setelah Diskon 20%:")
print("-" * 58)

for p in katalog[:4]:   # tampilkan 4 produk pertama saja
    harga_baru = p.harga_setelah_diskon(20)
    print(f"  {p.nama:<22} -> Rp {harga_baru:>10,.0f}")
# Output:
#   Laptop ASUS VivoBook   -> Rp  6,800,000
#   Mouse Wireless         -> Rp    120,000
#   Keyboard Mechanical    -> Rp    440,000
#   Buku Python OOP        -> Rp     96,000


# ??????????????????????????????????????????????????????????
# BAGIAN 5: SORTING (Mengurutkan Objek)
# ??????????????????????????????????????????????????????????
print("\n\n[INFO] 5. Urutkan Produk - Termahal ke Termurah:")
print("-" * 58)

terurut = sorted(katalog, key=lambda p: p.harga, reverse=True)
for i, p in enumerate(terurut, 1):
    print(f"  {i}. {p.nama:<22} -> Rp {p.harga:>10,.0f}")
# Output: urutan dari Laptop (8,5jt) -> Buku (120rb)


# ??????????????????????????????????????????????????????????
# BAGIAN 6: AGGREGATE (Hitung Statistik)
# ??????????????????????????????????????????????????????????
print("\n\n[INFO] 6. Statistik Katalog:")
print("-" * 58)

total_nilai   = sum(p.harga * p.stok for p in katalog)
harga_termahal = max(katalog, key=lambda p: p.harga)
harga_termurah = min(katalog, key=lambda p: p.harga)
rata_harga     = sum(p.harga for p in katalog) / len(katalog)

print(f"  Total nilai inventori : Rp {total_nilai:>15,.0f}")
print(f"  Produk termahal       : {harga_termahal.nama} (Rp {harga_termahal.harga:,.0f})")
print(f"  Produk termurah       : {harga_termurah.nama} (Rp {harga_termurah.harga:,.0f})")
print(f"  Rata-rata harga       : Rp {rata_harga:>10,.0f}")
# Output:
#   Total nilai inventori :   Rp  96,200,000
#   Produk termahal       : Laptop ASUS VivoBook (Rp 8,500,000)
#   Produk termurah       : Buku Python OOP (Rp 120,000)
#   Rata-rata harga       :  Rp  1,845,714


